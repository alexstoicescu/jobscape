import assert from 'node:assert/strict';
import {sourceModule} from './load-source.mjs';
const {hiringForResult, remoteEligibility} = await import(sourceModule('../lib/remote-eligibility.ts'));
const {matchesHiringRegion} = await import(sourceModule('../lib/hiring-regions.ts'));
const {hiringRegions} = await import(sourceModule('../lib/hiring-region-map.ts'));
assert.deepEqual(hiringRegions, ['All','Global remote','Unknown','EU','EMEA','APAC','US']);
const card = {title:'Engineer', snippet:'Fully remote worldwide.'};
const full = text => remoteEligibility({title:'Engineer', text, remote:true, locations:[], requirements:[], truncated:false, method:'structured'});
const match = (region, check, includeUnknown = false) => matchesHiringRegion(hiringForResult(card, check), region, includeUnknown, !!check);
assert.equal(match('All'), true);
assert.equal(match('Unknown'), true, 'Unchecked scope remains unestablished despite snippet hints');
assert.equal(match('Global remote', undefined, true), false);
const worldwide = full('Fully remote worldwide.');
assert.equal(match('Global remote', worldwide), true);
assert.equal(match('Unknown', worldwide), false);
assert.ok(worldwide.quotes.some(q => q.text === 'Fully remote worldwide.'));
const restricted = full('Fully remote worldwide. Candidates must reside in US only.');
assert.equal(match('Global remote', restricted, true), false);
assert.equal(match('EU', restricted, true), false, 'Full US restriction overrides worldwide snippet');
assert.equal(match('US', restricted), true);
for (const text of ['Remote.', 'We are a global company. Remote.', 'Our employer HQ is worldwide. Remote.', 'Remote role supporting worldwide customers.']) {
  const unknown = full(text);
  assert.equal(unknown.scope, 'Unknown', text);
  assert.equal(match('Unknown', unknown), true);
  assert.equal(match('Global remote', unknown, true), false);
  assert.equal(match('EU', unknown), false, 'Inconclusive full check overrides snippet');
  assert.equal(match('EU', unknown, true), true);
}
const loaded = [{...card, url:'one'}, {...card, url:'two'}];
const checks = {};
const cursor = {token:'saved', pages:2, hasMore:true};
const visible = filter => loaded.filter(row => matchesHiringRegion(hiringForResult(row, checks[row.url]), filter, true, !!checks[row.url]));
assert.equal(visible('Global remote').length, 0);
checks.one = worldwide;
assert.equal(visible('Global remote').length, 1, 'Count changes immediately on full-check update');
checks.one = restricted;
assert.equal(visible('Global remote').length, 0);
checks.two = full('Remote.');
assert.equal(visible('Unknown').length, 1);
assert.equal(visible('All').length, 2);
assert.deepEqual(cursor, {token:'saved', pages:2, hasMore:true});
assert.equal(loaded.length, 2);
console.log('Hiring filter checks passed: All, verified Global remote, unchecked/inconclusive Unknown, full-source precedence, quotes, immediate counts, retained cards and pagination.');
