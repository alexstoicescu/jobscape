import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {sourceModule} from './load-source.mjs';
const {googleQuery, matchesGoogleTitle, platforms} = await import(sourceModule('../lib/search.ts'));
const input = {keywords:'events',location:'',remote:true,platforms:platforms.map(p=>p.id)};
const query = googleQuery(input,input.platforms,'EU');
assert.ok(query.includes('(intitle:"events" OR intitle:"event")'));
assert.equal(matchesGoogleTitle('Backend Integration Engineer',input),false);
assert.equal(matchesGoogleTitle('Event Manager',input),true);
assert.equal(matchesGoogleTitle('Events Lead',input),true);
assert.equal(matchesGoogleTitle('Eventual Backend Engineer',input),false);
assert.equal(matchesGoogleTitle('Event-driven Architect for Enterprise Integration',input),true,
  'Known semantic defect reserved for PR #2: event-driven engineering still matches events.');
assert.equal(matchesGoogleTitle('Events Lead',{...input,keywords:'event'}),true);
assert.equal(matchesGoogleTitle('Backend Integration Engineer',{...input,wholePageKeywords:true}),true);
assert.equal(googleQuery({...input,wholePageKeywords:true}).includes('intitle:'),false);
const alternatives={...input,keywords:'events, community manager'};
assert.ok(googleQuery(alternatives).includes('intitle:"community manager"'));
assert.equal(matchesGoogleTitle('Senior Community Manager',alternatives),true);
assert.equal(matchesGoogleTitle('Community Engineer',alternatives),false);
const extractor=readFileSync(new URL('../extension/extract.js',import.meta.url),'utf8').replace('export async function','async function')+'\nextractGoogle({timeoutMs:5})';
const current='https://www.google.com/search?'+new URLSearchParams({q:query});
const link=(offset, label='', id='')=>({href:current+'&start='+offset,textContent:label,id,getAttribute:()=>null});
const anchor={href:'https://jobs.ashbyhq.com/example/job',parentElement:null};
const heading={textContent:'Events Manager',closest:selector=>selector==='a[href]'?anchor:null,querySelector:()=>null,getClientRects:()=>[{}]};
const run=(anchors,headings=[heading],text='Search results',image=false)=>vm.runInNewContext(extractor,{URL,setTimeout,clearTimeout,
  MutationObserver:class {observe(){} disconnect(){}},location:new URL(current),document:{readyState:'interactive',documentElement:{},addEventListener(){},removeEventListener(){},body:{innerText:text},querySelector:selector=>image&&selector.includes('imgres')?{}:null,querySelectorAll:selector=>selector==='a[href]'?anchors:headings}});
assert.equal((await run([link(20,'3'),link(10,'2')])).nextPage,current+'&start=10');
assert.equal((await run([link(10,'2'),link(20,'Weiter','pnnext')])).nextPage,current+'&start=20');
assert.equal((await run([link(0,'1'),{...link(10,'2'),href:'https://evil.example/search?start=10'}])).nextPage,null);
assert.equal((await run([])).nextPage,null);
assert.equal((await run([],[],'No results found')).empty,true);
assert.ok((await run([],[],'Unrecognized page structure')).error);
assert.equal((await run([],[],'Images',true)).code,'non_organic_layout');
assert.equal((await run([],[],'Before you continue to Google')).code,'consent');
assert.equal((await run([],[],'Our systems detected unusual traffic')).code,'verification');
const advert={...heading,closest:selector=>selector.includes('#tads')?{}:heading.closest(selector)};
const carousel={...heading,closest:selector=>selector.includes('g-scrolling-carousel')?{}:heading.closest(selector)};
const accessible={...heading,textContent:'Accessible Events Manager'};
assert.equal((await run([],[advert,carousel,accessible])).results.length,1,'Ads and image carousels cannot become organic cards');
assert.equal((await run([],[{...heading,getClientRects:()=>[]}])).results.length,0,'Hidden headings cannot become cards');
console.log('Title/pagination checks passed: event/events, intitle alternatives, returned-title rejection of snippet-only matches, opt-in whole-page mode, actual numbered/next links and empty-versus-extraction-failure distinction.');
