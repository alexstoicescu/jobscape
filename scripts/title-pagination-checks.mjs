import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {sourceModule} from './load-source.mjs';
const {googleQuery, matchesGoogleTitle, platforms} = await import(sourceModule('../lib/search.ts'));
const input = {keywords:'events',location:'',remote:true,platforms:platforms.map(p=>p.id)};
const query = googleQuery(input,input.platforms,'EU');
assert.ok(query.includes('(intitle:"events" OR intitle:"event")'));
assert.equal(matchesGoogleTitle('Backend Integration Engineer',input),false);
assert.equal(matchesGoogleTitle('Event Manager',input),true);
assert.equal(matchesGoogleTitle('Events Lead',input),true);
assert.equal(matchesGoogleTitle('Eventual Backend Engineer',input),false);
assert.equal(matchesGoogleTitle('Events Lead',{...input,keywords:'event'}),true);
assert.equal(matchesGoogleTitle('Backend Integration Engineer',{...input,wholePageKeywords:true}),true);
assert.equal(googleQuery({...input,wholePageKeywords:true}).includes('intitle:'),false);
const alternatives={...input,keywords:'events, community manager'};
assert.ok(googleQuery(alternatives).includes('intitle:"community manager"'));
assert.equal(matchesGoogleTitle('Senior Community Manager',alternatives),true);
assert.equal(matchesGoogleTitle('Community Engineer',alternatives),false);
const extractor=readFileSync(new URL('../extension/extract.js',import.meta.url),'utf8').replace('export function','function')+'\nextractGoogle()';
const current='https://www.google.com/search?'+new URLSearchParams({q:query});
const link=(offset, label='', id='')=>({href:current+'&start='+offset,textContent:label,id,getAttribute:()=>null});
const anchor={href:'https://jobs.ashbyhq.com/example/job',parentElement:null};
const heading={textContent:'Events Manager',closest:()=>anchor};
const run=(anchors,headings=[heading],text='Search results')=>vm.runInNewContext(extractor,{URL,location:new URL(current),document:{body:{innerText:text},querySelector:()=>null,querySelectorAll:selector=>selector==='a[href]'?anchors:headings}});
assert.equal(run([link(20,'3'),link(10,'2')]).nextPage,current+'&start=10');
assert.equal(run([link(10,'2'),link(20,'Weiter','pnnext')]).nextPage,current+'&start=20');
assert.equal(run([link(0,'1'),{...link(10,'2'),href:'https://evil.example/search?start=10'}]).nextPage,null);
assert.equal(run([]).nextPage,null);
assert.equal(run([],[],'No results found').empty,true);
assert.ok(run([],[],'Unrecognized page structure').error);
console.log('Title/pagination checks passed: event/events, intitle alternatives, returned-title rejection of snippet-only matches, opt-in whole-page mode, actual numbered/next links and empty-versus-extraction-failure distinction.');
